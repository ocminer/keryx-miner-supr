// libkeryx-llama-vk.so — the miner's in-process llama.cpp engine, AMD/Vulkan flavor (zero-dup).
//
// One in-process llama.cpp (Vulkan) instance per loaded model: it OWNS the resident GGUF copy on
// the inference GPU and this wrapper (a) builds a per-tensor prefix/address gather table over the
// SAME VRAM (buffer device addresses via the keryx_vk_* exports appended to ggml-vulkan by the
// build script), (b) runs the PoM possession walk over it (pom_walk_vk.comp — byte-identical math
// to the OpenCL/CUDA kernels), (c) serves a chunk-fetch verifier for the startup byte gate, and
// (d) generates OPoI text. Host-resident tensors (ggml keeps e.g. token_embd on the CPU buffer)
// are supplemented into a small wrapper-owned device buffer so every canonical chunk is
// GPU-reachable; supplement bytes are reported (0 = true zero-dup).
//
// The miner dlopens this next to its own binary; absent = the Vulkan llama-server subprocess and
// candle-CPU fallbacks stay active. Built by hiveos/build-keryx-llama-vk.sh against the SAME
// pinned llama.cpp as the CUDA flavor.
