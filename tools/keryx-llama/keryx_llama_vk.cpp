static constexpr uint64_t CHUNK_BYTES = 32;
static constexpr uint32_t NO_WINNER = 0xFFFFFFFFu;

struct PushWalk {
    uint64_t p[4];
    uint64_t t[4];
    uint64_t timestamp;
    uint64_t n_chunks;
    uint64_t start_nonce;
    uint32_t k;
    uint32_t batch;
    uint32_t n_tensors;
    uint32_t pad;
};
struct PushFetch {
    uint64_t first_chunk;
    uint32_t count;
    uint32_t n_tensors;
};

// Chunks per fetch dispatch (out buffer = this * 32 B = 4 MiB): the full-model spike sweeps the
// whole tier through this window; the startup byte gate fetches single chunks.
static constexpr uint32_t FETCH_WINDOW_CHUNKS = 131072;

